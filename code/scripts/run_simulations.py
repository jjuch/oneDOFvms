"""Run the closed-loop scenarios of Section 'Simulations', store results in
code/results/*.npz and write the metrics table paper/tables/sim_metrics.tex."""
import os
import pickle

import numpy as np

from common import RES, TAB
from vms import VMSParams
from vms.sim import Gains, Imperfections, simulate

P = VMSParams(11, 9)
T_END = 3000.0
IMP = Imperfections()  # ECC example: Ts = ks*Ts = ka*Ts = 0.03 s, gains -3 %/+6.5 %, noise, play

CASES = {
    "imperfect": ("Uncompensated", Gains()),
    "E": ("Energy ($u$)", Gains(KE=10)),
    "EA": ("Energy--amplitude ($u,s$)", Gains(KE=10, KA=1)),
    "ECC": ("ECC: $u,s,\\omega_z$ [batch]", Gains(KE=10, KA=1, phase_mode="freq", KO=1.0,
                                                   adaptive_projection=False)),
    "proposed": ("Proposed: $u,s$+PI, trim $c$", Gains(KE=10, KA=1, KIA=0.02, normalized=True,
                                                       phase_mode="trim", kP=0.02, kI=2e-4,
                                                       t_phase_on=200.0)),
}


def run(name, force=False):
    path = os.path.join(RES, f"sim_{name}.pkl")
    if os.path.exists(path) and not force:
        with open(path, "rb") as f:
            return pickle.load(f)
    label, g = CASES[name]
    r = simulate(P, IMP, g, T=T_END)
    eH, eA, psi = r.errors(projector=True)
    out = {"label": label, "t": r.t, "x": r.x, "u": r.u, "s": r.s, "omega_z": r.omega_z,
           "F": r.F, "c_trim": r.meta["c_trim"], "eH": eH, "eA": eA, "psi": psi,
           "metrics": r.metrics(), "Hr": r.Hr}
    with open(path, "wb") as f:
        pickle.dump(out, f)
    return out


def fmt(v):
    if not np.isfinite(v):
        return "--"
    if v == 0:
        return "$0$"
    e = int(np.floor(np.log10(abs(v))))
    if -2 <= e <= 1:
        return f"${v:.3g}$"
    m = v / 10**e
    return f"${m:.2g}{{\\times}}10^{{{e}}}$"


def main(force=False):
    rows = []
    for name in CASES:
        r = run(name, force)
        m = r["metrics"]
        rows.append((r["label"], m))
        print(f"{name:10s}", {k: float(f"{v:.3g}") for k, v in m.items()})
    lines = [
        "% generated by code/scripts/run_simulations.py -- do not edit by hand",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Case & RMS $|e_H|$ & RMS $|e_A|$ & $|\\hat r-\\tau/\\sigma|$ & $\\mathrm{med}_j\\min H_q/H_r$ & $\\varepsilon_{\\mathrm{cl}}$\\\\",
        "\\midrule",
        "Nominal (ideal) & $0$ & $0$ & $0$ & $0$ & $0$\\\\",
    ]
    for label, m in rows:
        lines.append(f"{label} & {fmt(m['rms_eH'])} & {fmt(m['rms_eA'])} & {fmt(m['eOmega'])} & "
                     f"{fmt(m['median_cycle_min_Hq'])} & {fmt(m['closure'])}\\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(TAB, "sim_metrics.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote paper/tables/sim_metrics.tex")


if __name__ == "__main__":
    import sys
    main(force="--force" in sys.argv)
